"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

const NAV = [
  { href: "/", label: "Dashboard", icon: DashboardIcon },
  { href: "/analytics", label: "Energy", icon: EnergyIcon },
  { href: "/schedules", label: "Schedule", icon: ScheduleIcon },
  { href: "/settings", label: "Settings", icon: SettingsIcon },
];

/** Mobile-only fixed bottom tab bar. Shown <=900px (see globals.css), where the
 *  top-bar nav pills are hidden. */
export function BottomNav() {
  const pathname = usePathname();
  return (
    <nav className="bottomnav" aria-label="Primary">
      {NAV.map((n) => {
        const Icon = n.icon;
        return (
          <Link key={n.href} href={n.href} className={`bni${pathname === n.href ? " active" : ""}`}>
            <Icon />
            <span>{n.label}</span>
          </Link>
        );
      })}
    </nav>
  );
}

